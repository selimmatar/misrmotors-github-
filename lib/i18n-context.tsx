// Context type
interface I18nContextType {
  language: Language
  setLanguage: (lang: Language) => void
  t: (key: TranslationKey) => string
  formatNumber: (num: number | null | undefined) => string
  formatCurrency: (amount: number | null | undefined, currency?: string) => string
  formatDate: (date: string | null | undefined) => string
  isRTL: boolean
}

const defaultT = (key: string) => {
  const value = translations.en[key]
  if (value) return value
  // Smart fallback: convert key to readable format
  return keyToReadable(key)
}

const defaultFormatNumber = (num: number | null | undefined) => {
  if (num === null || num === undefined || isNaN(num)) return "0"
  return num.toLocaleString("en-US")
}

const defaultFormatCurrency = (amount: number | null | undefined, currency = "EGP") => {
  if (amount === null || amount === undefined || isNaN(amount)) return `${currency} 0.00`
  return `${currency} ${amount.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

const defaultFormatDate = (date: string | null | undefined) => {
  if (!date) return ""
  try {
    return new Date(date).toLocaleDateString("en-US")
  } catch {
    return date
  }
}

const I18nContext = createContext<I18nContextType>({
  language: "en",
  setLanguage: () => {},
  t: defaultT,
  formatNumber: defaultFormatNumber,
  formatCurrency: defaultFormatCurrency,
  formatDate: defaultFormatDate,
  isRTL: false,
})

// Provider component
export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en")

  useEffect(() => {
    const saved = localStorage.getItem("language") as Language
    if (saved && (saved === "en" || saved === "ar")) {
      setLanguageState(saved)
    }
  }, [])

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    localStorage.setItem("language", lang)
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr"
    document.documentElement.lang = lang
  }

  useEffect(() => {
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr"
    document.documentElement.lang = language
  }, [language])

  const t = (key: TranslationKey): string => {
    const value = translations[language][key] || translations.en[key]
    if (value) return value

    // Track missing key for diagnostics (only once per key)
    if (!missingKeys.has(key)) {
      missingKeys.add(key)
      console.warn(`[i18n] Missing translation key: "${key}"`)
    }

    // Smart fallback: convert key to readable format
    return keyToReadable(key)
  }

  const formatNumber = (num: number | null | undefined): string => {
    if (num === null || num === undefined || isNaN(num)) {
      return language === "ar" ? "٠" : "0"
    }
    return num.toLocaleString(language === "ar" ? "ar-EG" : "en-US")
  }

  const formatCurrency = (amount: number | null | undefined, currency = "EGP"): string => {
    if (amount === null || amount === undefined || isNaN(amount)) {
      return language === "ar" ? `${currency} ٠٫٠٠` : `${currency} 0.00`
    }
    const formatted = amount.toLocaleString(language === "ar" ? "ar-EG" : "en-US", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })
    return `${currency} ${formatted}`
  }

  const formatDate = (date: string | null | undefined): string => {
    if (!date) return ""
    try {
      return new Date(date).toLocaleDateString(language === "ar" ? "ar-EG" : "en-US")
    } catch {
      return date
    }
  }

  return (
    <I18nContext.Provider
      value={{
        language,
        setLanguage,
        t,
        formatNumber,
        formatCurrency,
        formatDate,
        isRTL: language === "ar",
      }}
    >
      {children}
    </I18nContext.Provider>
  )
}

// Hook to use translations
export function useI18n() {
  return useContext(I18nContext)
}

// Export function to get missing keys for diagnostics
export function getMissingTranslationKeys(): string[] {
  return Array.from(missingKeys)
}

export type { Language, TranslationKey }
